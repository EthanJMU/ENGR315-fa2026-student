def parse_nyt_data(file_path=''):
    """
    Parse the NYT covid database and return a list of tuples. Each tuple describes one entry in the source data set.
    Date: the day on which the record was taken in YYYY-MM-DD format
    County: the county name within the State
    State: the US state for the entry
    Cases: the cumulative number of COVID-19 cases reported in that locality
    Deaths: the cumulative number of COVID-19 death in the locality

    :param file_path: Path to data file
    :return: A List of tuples containing (date,county, state, fips, cases, deaths) information

    ____________________ DO NOT MODIFY THIS FUNCTION ___________________
    """
    # data point list
    data=[]
 
    try:
        fin = open(file_path)
    except FileNotFoundError:
        print(file_path + ' not found.')
        sys.exit(-1)

    #delete header row
    fin.readline()

    # while parsing file    
    done = False
    while not done:
        line = fin.readline()

        if line == '':
            done = True
            continue

        # format of data is as follows
        (date, county, state, fips, cases, deaths) = line.rstrip().split(",")
        # clean up data and remove empty entries
        if cases=='':
            cases=0
        if deaths=='':
            deaths=0

        # convert elements into integers
        try:
            entry = (date, county, state, fips, int(cases), int(deaths))
        except ValueError:
            print('Invalid parse of ', line)
            raise ValueError("Invalid parse of line")
        # place entries as tuple into list
        data.append(entry)


    return data

def filter_location_data(data, county_name, state_name="Virginia"):
    """
    Filters raw dataset for a specific county and calculates daily new cases

    :param data: List of tuples from parse_nyt_data
    :param county_name: String name of county/city (e.g., 'Harrisonburg city')
    :param state_name: String state name (default 'Virginia')
    :return: List of dicts containing {'date': str, 'cumulative_cases': int, 'daily_new_cases': int}
    """
    filtered_records = []
    
    # Extract records matching the target county and state
    for record in data:
        rec_date, rec_county, rec_state, _, rec_cases, _ = record
        
        if rec_county == county_name and rec_state == state_name:
            filtered_records.append({
                'date': rec_date,
                'cumulative_cases': rec_cases
            })

    filtered_records.sort(key=lambda x: x['date'])

    processed_records = []
    prev_cumulative = 0
    
    for entry in filtered_records:
        current_cumulative = entry['cumulative_cases']
        daily_new = max(0, current_cumulative - prev_cumulative)
        
        processed_records.append({
            'date': entry['date'],
            'cumulative_cases': current_cumulative,
            'daily_new_cases': daily_new
        })
        
        prev_cumulative = current_cumulative

    return processed_records

def find_first_case_date(records):
    """
    Finds the first date with Covid cases.

    :param records: List of record dictionaries generated by filter_location_data
    :return: Date string (YYYY-MM-DD) or None if no cases found
    """
    for entry in records:
        if entry['cumulative_cases'] > 0:
            return entry['date']
    return None

def find_max_new_cases_date(records):
    """
    Finds the date with the highest new COVID-19 cases.

    :param records: List of record dictionaries
    :return: Tuple of (date_string, max_new_cases_count)
    """
    max_date = None
    max_cases = -1

    for entry in records:
        if entry['daily_new_cases'] > max_cases:
            max_cases = entry['daily_new_cases']
            max_date = entry['date']

    return max_date, max_cases

def find_worst_seven_day_period(records):
    """
    Finds the 7-day period with the most new COVID-19 cases.

    :param records: List of record dictionaries sorted by date
    :return: Tuple of (start_date, end_date, total_7day_cases)
    """
    worst_sum = -1
    worst_start_date = None
    worst_end_date = None

    for i in range(len(records) - 6):
        window = records[i : i + 7]
        window_sum = sum(day['daily_new_cases'] for day in window)

        if window_sum > worst_sum:
            worst_sum = window_sum
            worst_start_date = window[0]['date']
            worst_end_date = window[-1]['date']

    return worst_start_date, worst_end_date, worst_sum

